def verdict(lo: float, hi: float) -> str:
    """차이 AP(L) − AP(기준) 의 95% CI. 양수가 L이 좋은 쪽."""
    if lo > 0:
        return "L이 낫다"
    if hi < 0:
        return "L이 나쁘다"
    return "구분 불가"


def predictable(v1: str, v2: str) -> bool:
    return v1 == "L이 낫다" and v2 == "L이 낫다"
